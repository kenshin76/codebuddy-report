"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root=path.resolve(__dirname,"..");
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,"pricing.js"),"utf8"),sandbox);
const config=JSON.parse(fs.readFileSync(path.join(root,"report-config.json"),"utf8"));
const [pro,team]=config.pricing.plans;
const quote=sandbox.window.PLAN_PRICING.quote;
const snapshot=JSON.stringify(config.pricing);
for(const promotion of [false,true]) for(const yearly of [false,true]) for(const bonus of [false,true]) {
  const p=quote(pro,{promotion,yearly,bonus}), t=quote(team,{promotion,yearly,bonus});
  assert.equal(p.monthlyCents,yearly?800:promotion?1000:2000);
  assert.equal(t.monthlyCents,4000);
  assert.equal(p.billedCents,yearly?9600:promotion?1000:2000);
  assert.equal(t.billedCents,yearly?48000:4000);
  assert.equal(p.discountPercent,yearly?20:0);
  assert.equal(t.discountPercent,0);
  assert.equal(p.monthlyCredits,bonus?2000:1000);
  assert.equal(t.monthlyCredits,bonus?2000:1000);
  assert.equal(p.activityDays,30);
  assert.equal(p.activityCredits,1500);
  assert.equal(p.monthlyMaxCredits,bonus?3500:2500);
  assert.equal(t.activityCredits,null);
  assert.equal(t.monthlyMaxCredits,null);
  assert.equal(p.referenceOnly,!yearly && !promotion);
  assert.equal(p.promotionApplied,promotion && !yearly);
  assert.equal(t.promotionApplied,false);
  assert.equal(t.referenceOnly,false);
  assert.equal(p.billingPeriod,yearly?"year":"month");
}
assert.equal(quote(pro).monthlyCents,2000);
assert.equal(quote(pro).monthlyCredits,1000);
assert.equal(JSON.stringify(config.pricing),snapshot);
assert.equal(pro.dailyReward,50);
assert.equal(team.dailyReward,null);
assert.equal(quote({...team,dailyReward:0}).monthlyMaxCredits,1000);
assert.equal(pro.features[0],pro.featureHighlight);
assert.equal(team.features[0],"구독·구성원별 사용량 관리");
console.log("요금제 검사 통과: 8개 옵션 조합·기본값·할인 기준·30일 활동 보상·미표기와0 구분·원본 보존");
